/* Общая обвязка платы для обоих вариантов стенда. */

#ifndef BOARD_H
#define BOARD_H

/*
 * Подать внешнее 3.3 В на пин VCC платы. В zmk-варианте nice!nano это делает
 * узел EXT_POWER (gpio0 13, active high, задержка 50 мс); стенд собран на
 * базовой плате, где узла нет, поэтому поднимаем пин руками. Без этого панель
 * не питается вовсе и ловит паразитный ток только через защитные диоды
 * сигнальных линий.
 */
int ext_power_on(void);

/* Ждать, пока хост откроет порт: иначе первые строки уходят в никуда. */
void wait_for_console(void);

#endif /* BOARD_H */
