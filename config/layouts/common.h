#pragma once

/*
 * Сочетания, которые обрабатывает хост, а не прошивка.
 *
 * LANG_SWITCH обязан совпадать с опцией xkb в ОС (сейчас
 * grp:win_space_toggle, полная строка опций — в
 * ~/.config/shojiwm/src/index.tsx). При рассинхроне ru_en выдаёт мусор
 * на всех 14 символах, которых нет в ЙЦУКЕН, поэтому сочетание и живёт
 * одной строкой: менять его надо ровно здесь.
 *
 * Сам слой RU переключается не отсюда, а модулем ru-layer-sync по
 * HID-индикатору хоста; прошивка только шлёт сочетание.
 */
#define LANG_SWITCH LG(SPACE)
#define LAUNCHER    LG(A)

/*
 * Порядок модификаторов ASGC, заданный пальцем, а не рукой: от мизинца
 * внутрь ALT SHIFT GUI CTRL, справа зеркально — то есть отображение
 * «палец -> модификатор» у обеих рук одно и то же, и хват из двух
 * модификаторов всегда выходит на соседних пальцах.
 *
 * Порядок задан частотой аккордов, а не печати: CTRL (vim) указательным,
 * GUI (WM) средним, SHIFT безымянным, ALT мизинцем как почти
 * неиспользуемый. Конвенция GACS ставит SHIFT под указательный, потому
 * что при печати он самый частый, — здесь это не так: заглавные
 * набираются тапом липкого шифта, а не с HRM.
 *
 * Раньше порядок был выписан в семи местах (HRM обеих рук, модификаторы
 * на NAV и NUM в parity, NAV / NUM / MOD_L / MOD_R в instant), и менять
 * его надо было везде одновременно, иначе в одной раскладке оказывалось
 * два разных порядка.
 */
#define PINKY_MOD  LGUI
#define RING_MOD   LALT
#define MIDDLE_MOD LCTRL
#define INDEX_MOD  LSHFT
